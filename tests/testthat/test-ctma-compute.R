test_that('moving coordination preserves distinct and inherited host budgets', {
  a <- ctmaHost('studio1', workers=8, threads=3)
  b <- ctmaHost('studio2', workers=16)
  plan <- ctmaCompute(local=0, remote=list(a,b), threads=2,
                      coordinator=a, execution='background', tasks='likelihood')
  moved <- .ctmaComputeCoordinatorPlan(plan, tempdir())
  expect_equal(moved$local, 8L)
  expect_equal(moved$threads, 3L)
  expect_length(moved$remote, 1)
  expect_equal(moved$remote[[1]]$host, 'studio2')
  expect_equal(moved$remote[[1]]$workers, 16L)
  expect_equal(moved$remote[[1]]$threads, 2L)
  expect_null(moved$coordinator)
  expect_identical(moved$execution, 'foreground')
  expect_equal(plan$local, 0L)
  expect_null(plan$remote[[2]]$threads)
  plan$coordinator <- ctmaHost('controller')
  moved <- .ctmaComputeCoordinatorPlan(plan, tempdir())
  expect_equal(moved$local, 0L)
  expect_length(moved$remote, 2)
})
