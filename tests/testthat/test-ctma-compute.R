test_that('compute plans support multiple hosts and a controller without workers', {
  p <- ctmaCompute(workers=c(local=0,studio1=4,studio2=6),threads=2)
  expect_equal(p$local,0L);expect_length(p$remote,2)
  expect_equal(vapply(p$remote,`[[`,integer(1),'workers'),c(4L,6L))
  h <- ctmaHost('studio1',threads=3)
  expect_equal(h$threads,3L)
  expect_equal(ctmaCompute(local=0,remote=h,coordinator=h,execution='background')$coordinator,h)
})
test_that('invalid resource limits and unsafe connection identifiers fail before SSH', {
  for(x in list(-1,1.2,NA,Inf,TRUE)) expect_error(ctmaHost('host',workers=x))
  expect_error(ctmaHost('-oProxyCommand=touch'),'host')
  expect_error(ctmaHost('host',user='a;whoami'),'user')
  expect_error(ctmaHost('host',port=65536),'port')
  expect_error(ctmaHost('host',directory='/tmp/a;touch'),'directory')
  expect_error(ctmaCompute(workers=c(local=0)),'At least')
  expect_error(ctmaCompute(workers=c(a=1,a=2)),'unique')
  expect_error(ctmaCompute(tunnel='mosh'),'ssh')
})
test_that('plans contain no password argument or stored credential', {
  expect_false('password' %in% names(formals(ctmaHost)))
  expect_error(ctmaHost('host',password='not-a-real-password'),'unused')
  h <- ctmaHost('host',authentication='ask')
  expect_false(any(grepl('password|secret',names(h))))
})
test_that('compute binding keeps legacy calls and validates conflicts', {
  a <- list(maxiters=3L)
  expect_identical(.ctmaComputeBind(NULL,'julia',a,'ctmaFit'),a)
  p <- ctmaCompute(tasks='likelihood')
  b <- .ctmaComputeBind(p,'julia',a,'ctmaFit')
  expect_equal(b$maxiters,3L);expect_equal(b$julia_threads,1L)
  expect_error(.ctmaComputeBind(p,'stan',a,'ctmaFit'),'julia')
  expect_error(.ctmaComputeBind(p,'julia',list(parallel_starts=4),'ctmaFit'),'resource')
  expect_error(ctmaCompute(tasks='chains'), 'arg')
  studies <- ctmaCompute(tasks='studies')
  expect_identical(.ctmaComputeBind(studies,'ctsemjulia',a,'ctmaInit'),a)
  expect_error(.ctmaComputeBind(studies,'ctsemjulia',a,'ctmaFit'),'foreground ctmaInit')
})
