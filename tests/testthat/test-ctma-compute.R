test_that('durable job collection distinguishes complete and failed jobs', {
  path <- withr::local_tempdir()
  job <- structure(list(id='test',local=path,coordinator=NULL),class='ctmaJob')
  expect_identical(ctmaJobStatus(job)$state,'starting')
  saveRDS(list(state='failed',error='test error'),file.path(path,'status.rds'))
  expect_error(ctmaCollect(job),'test error')
  saveRDS(list(state='completed'),file.path(path,'status.rds'))
  expect_error(ctmaCollect(job),'no result')
  saveRDS(list(answer=42),file.path(path,'result.rds'))
  expect_equal(ctmaCollect(job),list(answer=42))
  expect_identical(ctmaResume(job),job)
})
