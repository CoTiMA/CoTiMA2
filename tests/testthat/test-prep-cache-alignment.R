test_that('legacy optimizer does not fabricate missing pooled wide-data caches',{
 study<-list(originalStudyNo=10,timePoints=2,empcov=diag(4),delta_t=1,sampleSize=2)
 x<-list(studyList=list(study))
 expect_message(z<-.ctmaOptimizePrepResult(x),'No study-wise wide-data cache')
 expect_false(z$reUseEmprawData);expect_null(z$emprawList)
 x$emprawList<-list(data.frame(matrix(0,2,5)))
 expect_silent(z<-.ctmaOptimizePrepResult(x));expect_true(z$reUseEmprawData)
 expect_identical(z$emprawList,x$emprawList)
})
