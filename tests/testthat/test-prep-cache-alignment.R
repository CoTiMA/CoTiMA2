test_that('multiple exclusions subset every original cache entry exactly once',{
 ids<-1:5
 x<-list(studyNumbers=as.list(ids),empcovs=lapply(ids,function(i)diag(i,2)),deltas=as.list(ids),sampleSizes=as.list(ids*10),startValues=as.list(ids+100),emprawList=lapply(ids,function(i)data.frame(v=i)),emprawLongList=lapply(ids,function(i)data.frame(v=i)),custom=lapply(ids,function(i)i+200),n.studies=5,summary=data.frame(matrix(1,5,8)))
 z<-.ctmaPrepExcludeStudies(x,c(2,4))
 expect_equal(unlist(z$studyNumbers),c(1,3,5));expect_equal(unlist(z$startValues),c(101,103,105))
 expect_equal(vapply(z$emprawList,function(d)d$v,numeric(1)),c(1,3,5))
 expect_equal(unlist(z$custom),c(201,203,205));expect_identical(dim(z$summary),c(5L,8L))
 expect_equal(z$n.studies,3);expect_equal(length(x$emprawList),5)
 expect_equal(.ctmaPrepExcludeStudies(x,999)$n.studies,5)
 expect_error(.ctmaPrepExcludeStudies(x,ids),'At least one')
 x$emprawList<-x$emprawList[1:4];expect_error(.ctmaPrepExcludeStudies(x,2),'not aligned')
})
